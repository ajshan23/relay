type Base = {
  bg: string;
  fg: string;
  card: string;
  muted: string;
  mutedFg: string;
  line: string;
  primary: string;
  primaryFg: string;
  soft: string;
  softFg: string;
  nav: string;
  navFg: string;
  navMuted: string;
  navActive: string;
  navLine: string;
  ai: string;
  aiFg: string;
  aiStrong: string;
  aiStrongFg: string;
  good: string;
  goodSoft: string;
  danger: string;
  dangerSoft: string;
};

export type Theme = {
  id: ThemeId;
  name: string;
  note: string;
  dark: boolean;
  swatch: [string, string, string];
  vars: Record<string, string>;
};

/** Expands a short palette into every variable the shadcn components and our own parts read. */
function build(b: Base): Record<string, string> {
  return {
    "--background": b.bg,
    "--foreground": b.fg,
    "--card": b.card,
    "--card-foreground": b.fg,
    "--popover": b.card,
    "--popover-foreground": b.fg,
    "--primary": b.primary,
    "--primary-foreground": b.primaryFg,
    "--secondary": b.muted,
    "--secondary-foreground": b.fg,
    "--muted": b.muted,
    "--muted-foreground": b.mutedFg,
    "--accent": b.soft,
    "--accent-foreground": b.softFg,
    "--destructive": b.danger,
    "--border": b.line,
    "--input": b.line,
    "--ring": b.primary,
    "--nav": b.nav,
    "--nav-foreground": b.navFg,
    "--nav-muted": b.navMuted,
    "--nav-active": b.navActive,
    "--nav-border": b.navLine,
    "--ai": b.ai,
    "--ai-foreground": b.aiFg,
    "--ai-strong": b.aiStrong,
    "--ai-strong-foreground": b.aiStrongFg,
    "--good": b.good,
    "--good-soft": b.goodSoft,
    "--danger-soft": b.dangerSoft,
  };
}

